/* ── Helpers ── */

export function getArticle(slug: string): MagArticle | undefined {
  return ARTICLES.find((a) => a.slug === slug)
}

/** Related articles: same category first, then the rest (max 3). */
export function relatedArticles(current: MagArticle, max = 3): MagArticle[] {
  const others = ARTICLES.filter((a) => a.slug !== current.slug)
  const sameCat = others.filter((a) => a.category === current.category)
  const rest = others.filter((a) => a.category !== current.category)
  return [...sameCat, ...rest].slice(0, max)
}
